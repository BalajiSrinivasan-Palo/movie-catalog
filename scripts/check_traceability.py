#!/usr/bin/env python3
"""Fail if requirements, BRD acceptance criteria or edge cases have no owning story.

Reads docs/requirements/BRD.md, docs/requirements/NFR.md, docs/backlog/stories/*.md and
docs/backlog/definition-of-done.md. Writes docs/backlog/coverage-report.md. Exit 1 on any gap.
"""
import re, sys, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
brd = (root/"docs/requirements/BRD.md").read_text()
nfr = (root/"docs/requirements/NFR.md").read_text()
dod = (root/"docs/backlog/definition-of-done.md").read_text()
stories = {p.stem: p.read_text() for p in sorted((root/"docs/backlog/stories").glob("S-*.md"))}

frs  = set(re.findall(r'^\| (FR-[A-Z]+-\d+) \|', brd, re.M))
nfrs = set(re.findall(r'^\| (NFR-[A-Z0-9]+-\d+) \|', nfr, re.M))
acs  = set(re.findall(r'^\| (AC-FR-[A-Z]+-\d+-\d+) \|', brd, re.M))
ecs  = set(re.findall(r'^\| (EC-\d+) \|', brd, re.M))
brs  = set(re.findall(r'^\| (BR-\d+) \|', brd, re.M))

def field(text, name):
    m = re.search(r'\*\*%s:\*\*\s*(.*)' % re.escape(name), text)
    return [x.strip() for x in m.group(1).split(',')] if m and m.group(1).strip() not in ('none','') else []

req_to_st, ac_owner = {}, {}
errors = []
for sid, t in stories.items():
    for r in field(t, "Requirements"):
        req_to_st.setdefault(r, []).append(sid)
    for a in field(t, "BRD acceptance criteria owned"):
        ac_owner.setdefault(a, []).append(sid)
    for d in field(t, "Depends on"):
        if d not in stories: errors.append(f"{sid}: unknown dependency {d}")
dod_nfrs = set(re.findall(r'NFR-[A-Z0-9]+-\d+', dod.split("Cross-cutting", 1)[-1]))

gaps = []
for f in sorted(frs):
    if f not in req_to_st: gaps.append(f"{f}: no story")
for n in sorted(nfrs):
    if n not in req_to_st and n not in dod_nfrs: gaps.append(f"{n}: no story and not cross-cutting")
for a in sorted(acs):
    o = ac_owner.get(a, [])
    if len(o) != 1: gaps.append(f"{a}: owned by {len(o)} stories ({', '.join(o)})")
for a in ac_owner:
    if a not in acs: gaps.append(f"{a}: owned but not defined in BRD")
for f in sorted(frs):  # every FR should have at least one owned AC
    if not any(a.startswith("AC-"+f+"-") for a in ac_owner) and f not in ("FR-MOV-02",) and not any(a.startswith("AC-"+f+"-") for a in acs):
        gaps.append(f"{f}: has no acceptance criterion")
mentioned = set()
for t in stories.values(): mentioned |= set(re.findall(r'EC-\d+', t)) | set(re.findall(r'BR-\d+', t))
for e in sorted(ecs | brs):
    if e not in mentioned: gaps.append(f"{e}: edge case/business rule not referenced by any story")

out = ["# Backlog Coverage Report", "", "Generated by `scripts/check_traceability.py`. Shows planning coverage only, not test results.", "",
       f"- Functional requirements: {len(frs)}; NFRs: {len(nfrs)}; BRD acceptance criteria: {len(acs)}; edge cases: {len(ecs)}; business rules: {len(brs)}; stories: {len(stories)}", ""]
out += ["## Requirement to stories", "", "| Requirement | Stories |", "|-------------|---------|"]
for r in sorted(frs | nfrs):
    s = ", ".join(req_to_st.get(r, [])) or ("(cross-cutting DoD)" if r in dod_nfrs else "**NONE**")
    out.append(f"| {r} | {s} |")
out += ["", "## BRD acceptance criterion to owning story", "", "| AC | Story |", "|----|-------|"]
for a in sorted(acs): out.append(f"| {a} | {', '.join(ac_owner.get(a, [])) or '**NONE**'} |")
out += ["", "## Result", ""]
out += (["**GAPS FOUND:**", ""] + [f"- {g}" for g in gaps + errors]) if (gaps or errors) else ["No gaps found."]
(root/"docs/backlog/coverage-report.md").write_text("\n".join(out) + "\n")
print("\n".join(gaps + errors) or "OK: no gaps")
sys.exit(1 if (gaps or errors) else 0)
